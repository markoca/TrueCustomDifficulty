#!/usr/bin/env python3
"""Generate deterministic writer-shape fixtures for World Weapon Shuffle.

This intentionally uses a fixed audit ordering/replacement choice rather than pretending to
execute System.Random. Its purpose is to lock the exact CFG/BPatch shape emitted for 25/50/100%
and to verify that only the replacement PossibleItems node is materialized.
"""
import csv, math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'tests/world-weapon-shuffle-fixtures'
slots=list(csv.DictReader(open(ROOT/'Data/world-weapon-shuffle-manifest.csv',encoding='utf8')))
pool=list(csv.DictReader(open(ROOT/'Data/world-weapon-shuffle-pool.csv',encoding='utf8')))
compat=[]
for s in sorted(slots,key=lambda x:x['generator_sid']):
    alts=sorted([p for p in pool if p['tier']==s['progression_tier'] and p['family']==s['family'] and p['item_sid']!=s['item_sid']],key=lambda x:x['item_sid'])
    if alts: compat.append((s,alts))
assert len(compat)==8

def render(rows):
    lines=['// Generated by True Custom Difficulty.','// BPatch source: GameData/ItemGeneratorPrototypes.cfg','// Only values changed by the active preset are emitted.','']
    for s,alt in sorted(rows,key=lambda x:x[0]['generator_sid']):
        path=s['node_path'].split('/')
        lines += [f"{s['generator_sid']} : struct.begin {{bpatch}}",
                  f"    {path[0]} : struct.begin {{bpatch}}",
                  f"        {path[1]} : struct.begin {{bpatch}}",
                  f"            {path[2]} : struct.begin {{bpatch}}",
                  f"                {path[3]} : struct.begin"]
        vals={'ItemPrototypeSID':alt['item_sid'],'Chance':s['chance'],'Weight':s['weight'],'MinDurability':s['mindurability'],'MaxDurability':s['maxdurability'],'AmmoMinCount':s['ammomincount'],'AmmoMaxCount':s['ammomaxcount'],'MinCount':s['mincount'],'MaxCount':s['maxcount']}
        # Current CfgNaturalComparer is ordinal for these assignment names.
        for k in sorted(k for k,v in vals.items() if v.strip()): lines.append(f"                    {k} = {vals[k]}")
        lines += ['                struct.end','            struct.end','        struct.end','    struct.end','struct.end','']
    return '\n'.join(lines).rstrip()+'\n'

summary=[]
for frac in (.25,.50,1.0):
    n=int(math.floor(len(compat)*frac+0.5))
    chosen=[(s,alts[0]) for s,alts in compat[:n]]
    pct=int(frac*100)
    (OUT/f'world-weapon-shuffle-{pct}.cfg').write_text(render(chosen),encoding='utf8')
    summary.append((pct,n,[s['generator_sid'] for s,_ in chosen]))
assert set(summary[0][2]) <= set(summary[1][2]) <= set(summary[2][2])
print('[OK] writer-shape fixtures generated: 25%=2 / 50%=4 / 100%=8')
print('[OK] fixture slot sets are nested: 25% <= 50% <= 100%')
