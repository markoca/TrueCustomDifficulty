#!/usr/bin/env python3
"""Generate isolated BPatch staging trees for runtime-proof candidates.

This tool emits deterministic A/B overrides from the same locked audit surfaces now used by the production UI/writer. It remains test-only and does not change runtime-verification status.
"""
from __future__ import annotations

import argparse
import csv
import shutil
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEAPON_CSV = ROOT / "npc-weapon-production-entries.csv"
GENERATOR_CSV = ROOT / "generator-local-source-item-entries.csv"

TESTS = {
    "weapon-condition": {
        "low": {"MinDurability": "0.01", "MaxDurability": "0.05"},
        "high": {"MinDurability": "0.95", "MaxDurability": "1.0"},
    },
    "weapon-ammo": {
        "low": {"AmmoMinCount": "1", "__ammo_max__": "1"},
        "high": {"AmmoMinCount": "77", "__ammo_max__": "77"},
    },
    "medic-stock": {
        "low": {"MinCount": "1", "MaxCount": "1"},
        "high": {"MinCount": "20", "MaxCount": "20"},
    },
}


def read_csv(path: Path):
    with path.open(newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def weapon_rows():
    rows = read_csv(WEAPON_CSV)
    if len(rows) != 121 or len({r["generator_sid"] for r in rows}) != 33:
        raise SystemExit("weapon runtime surface drifted; expected 121 rows / 33 roots")
    return rows


def medic_rows():
    rows = [r for r in read_csv(GENERATOR_CSV)
            if r.get("sid") in {"MedicUniversal_TradeItemGenerator", "MedicNoon_TradeItemGenerator"}
            and r.get("ItemPrototypeSID")]
    u = sum(r["sid"] == "MedicUniversal_TradeItemGenerator" for r in rows)
    n = sum(r["sid"] == "MedicNoon_TradeItemGenerator" for r in rows)
    if (len(rows), u, n) != (48, 25, 23):
        raise SystemExit(f"medic runtime surface drifted; got {len(rows)}/{u}/{n}, expected 48/25/23")
    if any(not r.get("MinCount") or not r.get("MaxCount") for r in rows):
        raise SystemExit("medic runtime surface contains a row without MinCount/MaxCount")
    return rows


def scope_file(scope: str) -> str:
    s = (scope or "").strip().lower()
    if s in {"base", "basegame"}:
        return "GameData/ItemGeneratorPrototypes.cfg"
    if s in {"dlc1", "dlc"}:
        return "DLCGameData/DLC1/ItemGeneratorPrototypes.cfg"
    raise SystemExit(f"unsupported scope in runtime surface: {scope!r}")


def output_file(root: Path, logical_file: str) -> Path:
    rel = Path(logical_file)
    stem = rel.stem
    return (root / "Stalker2" / "Content" / "GameLite" / rel.parent /
            stem / f"{stem}_patch_TCDRuntimeTest.cfg")


def natural_index(value: str) -> int:
    v = value.strip()
    if v.startswith("[") and v.endswith("]"):
        try:
            return int(v[1:-1])
        except ValueError:
            pass
    return 10**9


def render(test: str, variant: str, rows, assignments) -> dict[str, str]:
    # file -> generator -> category -> entry -> assignments
    tree = defaultdict(lambda: defaultdict(lambda: defaultdict(dict)))
    for r in rows:
        logical = scope_file(r["scope"])
        sid = r.get("generator_sid") or r.get("sid")
        cat = r["category_node"]
        ent = r["entry_node"]
        vals = dict(assignments)
        if "__ammo_max__" in vals:
            max_value = vals.pop("__ammo_max__")
            max_field = r.get("ammo_max_field") or ("AmmoMaxcount" if r.get("AmmoMaxcount") else "AmmoMaxCount")
            if max_field not in {"AmmoMaxCount", "AmmoMaxcount"}:
                raise SystemExit(f"unexpected ammo max field for {sid} {cat}/{ent}: {max_field!r}")
            vals[max_field] = max_value
        tree[logical][sid][cat][ent] = vals

    rendered = {}
    for logical, generators in tree.items():
        out = [
            "// Generated by TCD runtime-test tooling. TEST ONLY - not a production preset.",
            f"// Runtime test: {test} / {variant}",
            f"// BPatch source: {logical}",
            "// Change only the fields required by the locked runtime-proof contract.",
            "",
        ]
        for sid in sorted(generators):
            out.append(f"{sid} : struct.begin {{bpatch}}")
            out.append("    ItemGenerator : struct.begin {bpatch}")
            for cat in sorted(generators[sid], key=natural_index):
                out.append(f"        {cat} : struct.begin {{bpatch}}")
                out.append("            PossibleItems : struct.begin {bpatch}")
                for ent in sorted(generators[sid][cat], key=natural_index):
                    out.append(f"                {ent} : struct.begin {{bpatch}}")
                    for key in sorted(generators[sid][cat][ent]):
                        out.append(f"                    {key} = {generators[sid][cat][ent][key]}")
                    out.append("                struct.end")
                out.append("            struct.end")
                out.append("        struct.end")
            out.append("    struct.end")
            out.append("struct.end")
            out.append("")
        rendered[logical] = "\n".join(out).rstrip() + "\n"
    return rendered


def generate(test: str, variant: str, out_root: Path):
    if test in {"weapon-condition", "weapon-ammo"}:
        rows = weapon_rows()
    else:
        rows = medic_rows()
    docs = render(test, variant, rows, TESTS[test][variant])
    if out_root.exists():
        shutil.rmtree(out_root)
    for logical, content in docs.items():
        path = output_file(out_root, logical)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return len(rows), len(docs)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--test", choices=sorted(TESTS), required=True)
    ap.add_argument("--variant", choices=["low", "high"], required=True)
    ap.add_argument("--output", type=Path, required=True,
                    help="staging root to recreate and populate")
    args = ap.parse_args()
    rows, files = generate(args.test, args.variant, args.output.resolve())
    print(f"[OK] {args.test}/{args.variant}: {rows} rows -> {files} BPatch file(s)")
    print(f"[OK] staging root: {args.output.resolve()}")


if __name__ == "__main__":
    main()
