"""Build docs/combat/MUTANT-COOLDOWNS.md: real cooldown seconds per mutant family,
split into the ATTACKS / ABILITIES groups of MutantAggressionPolicy.

Usage: python3 tools/build_mutant_cooldown_table.py <base GameData> <DLC1 dir>
"""
import collections
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from mutant_cooldown_extract import extract, parse  # noqa: E402

POLICY = ROOT / "src/TrueCustomDifficulty/Services/MutantAggressionPolicy.cs"
OUT = ROOT / "docs/combat/MUTANT-COOLDOWNS.md"

MOVE = {
    "ClawAttack": "claw / turn swipe", "BiteAttack": "bite", "BiteAttackAnyAngle": "bite from any angle",
    "RunAttack": "running attack", "JumpAttack": "leap", "ShortJumpAttack": "short leap",
    "LongJumpAttack": "long leap", "KickAttack": "kick", "Charge": "charge", "JumpToEnemy": "jump to enemy",
    "FlyThrough": "fly-through", "Evasion": "dodge", "AOEAttack": "area burst",
    "Abilities.PSYAttack": "psy strike", "Abilities.RaiseDeadBody": "raise corpse",
    "Abilities.ZombifyNPC": "zombify", "Roar": "roar", "Growl": "growl", "BlinkTeleport": "teleport",
    "Shield": "shield", "Throw": "throw", "ThrowGrenade": "grenade throw queue", "WeaponDrag": "disarm",
    "WeaponRiseAndShoot": "raise weapons and shoot", "ActivateAnomaly": "spawn anomaly",
    "ShockwaveAttack": "shockwave", "Howl": "howl", "CombatSummon": "summon", "RetreatSummon": "retreat summon",
    "TrickSound.Mimicry": "mimic sound", "TrickSound.Mockery": "mocking sound", "TrickSound.Ambush": "ambush sound",
    "Squeek": "squeal", "Grunt": "grunt", "Alerted": "alert reaction", "Summon": "summon phantom",
}
# Special agents: shown as notes, never as the family value.
SPECIAL = re.compile(r"PhantomAttack|NoCooldowns|JadedChimera|DLC01|SpatialBubble|E10_MQ01|Prologue|"
                     r"Yaniv|ShootingSpecial|Mist|ThrowExplosivesOnly|Collar_PSYAttack")
# Generic abilities without a family in their SID (used by Bloodsucker / MistBloodsucker).
GENERIC = {"RoarAbility": "bloodsucker"}


def policy():
    src = re.sub(r"//[^\n]*", "", POLICY.read_text(encoding="utf-8"))
    fams = {}
    for m in re.finditer(r'new\("(\w+)", "([^"]+)", new\[\](.*?)\},?\s*T\(([^)]*)\),\s*'
                         r'(?:T\(([^)]*)\)|Array\.Empty<string>\(\))', src, re.S):
        agents = re.findall(r'A\("(\w+)"((?:, "[\w.]+")*)\)', m.group(3))
        master = set(re.findall(r'"([\w.]+)"', agents[0][1])) if agents else set()
        fams[m.group(1)] = dict(label=m.group(2), attack=re.findall(r'"([\w.]+)"', m.group(4)),
                                ability=re.findall(r'"([\w.]+)"', m.group(5) or ""), master=master)
    return fams


def fmt(x):
    return f"{x:g}"


def main():
    base, dlc = sys.argv[1], sys.argv[2]
    rows = extract(str(Path(base) / "AbilityPrototypes.cfg"), str(Path(dlc) / "AbilityPrototypes.cfg"))
    tops, _ = parse(str(Path(base) / "AbilityPrototypes.cfg"))
    for sid, fam in GENERIC.items():
        tc = [k for k in tops[sid]["kids"] if k["name"] == "TriggeredCooldowns"][0]["kids"][0]
        rows.append(dict(src="base", fam=fam, ability=sid, tag="Roar",
                         dur=float(dict(tc["kv"])["Duration"].rstrip("f").rstrip("."))))
    fams = policy()
    by = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows:
        by[r["fam"]][r["tag"]].append(r)

    out = ["# Mutant cooldowns: real seconds per family", "",
           "Generated by `tools/build_mutant_cooldown_table.py` from the base and DLC1 "
           "`AbilityPrototypes.cfg` (own `CooldownTag` → `TriggeredCooldowns.Duration`, refkey-resolved).",
           "Do not edit by hand.", "",
           "* **Normal** = Novice, Stalker and Veteran. **Master** = what the game uses on Master: "
           "the difficulty halves the tags it lists for the family's main agent (`AgentCooldownMultipliers` 0.5).",
           "* A family's ATTACKS slider at rate *r* divides every attack time by *r* (2× = half the wait). "
           "ABILITIES have no slider: each ability is its own knob. On Master a vanilla is 2× where the game already halves.",
           "* Every covered row also has its own knob under its slider (`combat.mutantMoveRate.{family}.{move}`); "
           "an attack's time is divided by slider × knob, an ability's by its knob. Moves at 0 s have no knob.",
           "* **Vanilla only** rows have no control: roars, growls, howls, dodges, teleports, shields, alert sounds and moves the game never triggers "
           "(see `MUTANT-ABILITIES-CATALOG.md`).",
           "* Special and story variants (phantoms, Prologue, Mist, `Collar` psy, DLC1 bosses, "
           "`ShootingSpecial`, `NoCooldowns`) are listed under *Variants* and never set the family value.",
           ""]
    for key in sorted(by):
        f = fams.get(key)
        if not f:
            continue
        out += [f"## {f['label']}", "", "| Group | Move | Tag | Normal | Master | Variants |", "|---|---|---|---|---|---|"]
        lines = []
        for tag, rs in by[key].items():
            full = tag
            group = ("ATTACKS" if tag in f["attack"] else "ABILITIES" if tag in f["ability"]
                     else "vanilla only")
            normal = sorted({r["dur"] for r in rs if not SPECIAL.search(r["ability"]) and r["src"] == "base"})
            special = sorted({(r["dur"], r["ability"]) for r in rs if SPECIAL.search(r["ability"]) or r["src"] == "dlc"})
            if not normal:
                normal = sorted({d for d, _ in special})
                special = []
            n = " / ".join(fmt(x) + " s" for x in normal)
            m = " / ".join(fmt(x * (0.5 if full in f["master"] else 1)) + " s" for x in normal)
            var = "; ".join(f"{a} {fmt(d)} s" for d, a in special if d not in normal)
            order = {"ATTACKS": 0, "ABILITIES": 1, "SUMMON RATE": 2, "vanilla only": 3}[group]
            lines.append((order, normal[0] if normal else 0, f"| {group} | {MOVE.get(tag, tag)} | `{tag}` | {n} | "
                                                             f"{m if m != n else '='} | {var} |"))
        out += [x[2] for x in sorted(lines)] + [""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
