using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using TrueCustomDifficulty.ViewModels;

namespace TrueCustomDifficulty.Services;

public sealed partial class CfgPatchWriterService
{
    private const string WorldArmorDirectResource =
        "TrueCustomDifficulty.Data.world-armor-direct-manifest.csv";
    private const string WorldArmorStashResource =
        "TrueCustomDifficulty.Data.world-armor-stash-manifest.csv";

    // A single opt-in suppresses only individually audited, ordinary wearable
    // world loot. Never blanket-delete an armor item SID or a shared generator.
    private static (int EditCount, int FileCount) WriteWorldArmorRemovals(
        IReadOnlyDictionary<string, ParameterViewModel> modifiedById,
        IReadOnlyDictionary<string, ParameterViewModel> allById,
        bool hasDlc1,
        string outputRoot,
        IDictionary<string, PatchDocument> documents,
        ISet<string> writtenParameters)
    {
        const string id = "loot.worldArmorRemoved";
        if (!modifiedById.ContainsKey(id))
            return (0, 0);
        if (!allById.TryGetValue(id, out var toggle) || !toggle.IsToggle)
            throw new InvalidDataException("Missing world armor removal checkbox.");
        writtenParameters.Add(id);
        if (!toggle.CurrentBoolean)
            return (0, 0);

        var direct = ReadStashCsv(WorldArmorDirectResource, 6);
        var stash = ReadStashCsv(WorldArmorStashResource, 5);
        if (direct.Count != 94
            || direct.Count(x => x[0] == "baseGame") != 76
            || direct.Count(x => x[0] == "dlc1") != 18
            || direct.Count(x => x[5] == "Armor") != 74
            || direct.Count(x => x[5] == "Helmet") != 20
            || stash.Count != 6)
            throw new InvalidDataException("World armor source inventory drifted.");

        var directIds = new HashSet<string>(StringComparer.Ordinal);
        foreach (var row in direct)
        {
            var expectedSource = row[0] switch
            {
                "baseGame" => "GameData/SpawnActorPrototypes.cfg",
                "dlc1" => "DLCGameData/DLC1/SpawnActorPrototypes.cfg",
                _ => throw new InvalidDataException("Unknown world armor scope.")
            };
            var suffix = row[5] switch
            {
                "Armor" => "_Armor",
                "Helmet" => "_Helmet",
                _ => throw new InvalidDataException("Unknown world armor item category.")
            };
            if (row[1] != expectedSource || row[2] != "WorldMap_WP"
                || row[3].Length != 32 || !row[3].All(Uri.IsHexDigit)
                || !directIds.Add(row[3])
                || !row[4].EndsWith(suffix, StringComparison.Ordinal)
                || row[4].Contains("X7", StringComparison.OrdinalIgnoreCase))
                throw new InvalidDataException("Unsafe world armor actor " + row[3]);
        }

        // All six item nodes belong to ordinary, non-quest physical stash actors.
        // Shared generators and named-clue/quest actors are not allowed.
        var regular = LoadSmartStashActors()
            .Where(x => x.ClueSid == "EmptyInherited")
            .Select(x => x.ActorSid).ToHashSet(StringComparer.Ordinal);
        var stashActors = new HashSet<string>(StringComparer.Ordinal);
        var stashGenerators = new HashSet<string>(StringComparer.Ordinal);
        foreach (var row in stash)
        {
            if (row[0].Length != 32 || !row[0].All(Uri.IsHexDigit)
                || !stashActors.Add(row[0]) || !stashGenerators.Add(row[1])
                || !regular.Contains(row[0])
                || BaseProtectedStashActors.Value.Contains(row[0])
                || !row[1].EndsWith("_" + row[0], StringComparison.Ordinal)
                || row[3] != "Head" || !row[2].EndsWith("_Helmet", StringComparison.Ordinal)
                || row[4] != "ItemGenerator/[1]/PossibleItems/[0]")
                throw new InvalidDataException("Unsafe stash armor entry " + row[1]);
        }

        var edits = 0;
        var files = 0;
        foreach (var row in direct.Where(x => IsScopeApplicable(x[0], hasDlc1)))
        {
            var path = GetSpawnActorRemovalOutputPath(
                outputRoot, row[1], row[2], row[3]);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path,
                "// Generated by True Custom Difficulty." + Environment.NewLine +
                "// Safe non-quest world suit or helmet removal." + Environment.NewLine +
                row[3] + " : removenode" + Environment.NewLine,
                new UTF8Encoding(false));
            edits++;
            files++;
        }

        var document = GetDocument(documents, "GameData/ItemGeneratorPrototypes.cfg");
        foreach (var row in stash)
        {
            var path = row[4].Split('/', StringSplitOptions.RemoveEmptyEntries);
            document.AddRemovalNode(row[1], path[..^1], path[^1]);
            edits++;
        }
        return (edits, files);
    }
}
