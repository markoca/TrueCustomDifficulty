using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using TrueCustomDifficulty.ViewModels;

namespace TrueCustomDifficulty.Services;

public sealed partial class CfgPatchWriterService
{
    public const string LooseOpticsRemovedId = "loot.looseOpticsRemoved";
    private const string LooseOpticsManifestResource =
        "TrueCustomDifficulty.Data.loose-optics-direct-manifest.csv";

    // Exact source-approved WorldMap direct pickups only: never change a shared
    // item prototype, named/quest actor, NPC NVG pool, merchant, or stash.
    private static int WriteLooseOpticsRemovals(
        IReadOnlyDictionary<string, ParameterViewModel> modifiedById,
        IReadOnlyDictionary<string, ParameterViewModel> allById,
        bool hasDlc1, string outputRoot, ISet<string> writtenParameters)
    {
        if (!modifiedById.ContainsKey(LooseOpticsRemovedId))
            return 0;
        if (!allById.TryGetValue(LooseOpticsRemovedId, out var toggle) || !toggle.IsToggle)
            throw new InvalidDataException("Missing loose binocular/NVG removal checkbox.");
        writtenParameters.Add(LooseOpticsRemovedId);
        if (!toggle.CurrentBoolean)
            return 0;

        var rows = ReadStashCsv(LooseOpticsManifestResource, 5);
        if (rows.Count != 17
            || rows.Count(row => row[0] == "baseGame") != 15
            || rows.Count(row => row[0] == "dlc1") != 2
            || rows.Count(row => row[4].StartsWith("Binoculars_", StringComparison.Ordinal)) != 13
            || rows.Count(row => row[4].StartsWith("NVG_Gen", StringComparison.Ordinal)) != 4)
            throw new InvalidDataException("World binocular/NVG actor inventory drifted.");

        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (var row in rows)
        {
            var source = row[0] switch
            {
                "baseGame" => "GameData/SpawnActorPrototypes.cfg",
                "dlc1" => "DLCGameData/DLC1/SpawnActorPrototypes.cfg",
                _ => throw new InvalidDataException("Unknown loose optics scope.")
            };
            if (row[1] != source || row[2] != "WorldMap_WP"
                || row[3].Length != 32 || !row[3].All(Uri.IsHexDigit)
                || !ids.Add(row[3])
                || !(row[4] is "Binoculars_01" or "Binoculars_02" or "Binoculars_03"
                    or "NVG_Gen1" or "NVG_Gen2" or "NVG_Gen3"))
                throw new InvalidDataException("Unsafe WorldMap optics actor: " + row[3]);
        }

        var edits = 0;
        foreach (var row in rows.Where(row => IsScopeApplicable(row[0], hasDlc1)))
        {
            var path = GetSpawnActorRemovalOutputPath(outputRoot, row[1], row[2], row[3]);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path,
                "// Generated by True Custom Difficulty." + Environment.NewLine +
                "// Audited non-quest direct binocular/NVG pickup: " + row[4] + Environment.NewLine +
                row[3] + " : removenode" + Environment.NewLine,
                new UTF8Encoding(false));
            edits++;
        }
        return edits;
    }
}
