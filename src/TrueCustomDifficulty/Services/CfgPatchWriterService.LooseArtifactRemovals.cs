using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using TrueCustomDifficulty.ViewModels;

namespace TrueCustomDifficulty.Services;

public sealed partial class CfgPatchWriterService
{
    public const string LooseArtifactsRemovedId = "loot.looseArtifactsRemoved";

    private const string LooseArtifactManifestResource =
        "TrueCustomDifficulty.Data.loose-artifact-spawner-manifest.csv";

    // The only fixed, non-quest artifact spots outside anomaly fields: the
    // single-artifact Weird* spawners (base) and one DLC1 WaterDrip spawner.
    // Anomaly-field spawners (Universal*, LesserZone*), quest spawners and the
    // quest-referenced WaterDrip actors are never listed.
    private static int WriteLooseArtifactRemovals(
        IReadOnlyDictionary<string, ParameterViewModel> modifiedById,
        IReadOnlyDictionary<string, ParameterViewModel> allById,
        bool hasDlc1,
        string outputRoot,
        ISet<string> writtenParameters)
    {
        if (!modifiedById.ContainsKey(LooseArtifactsRemovedId))
            return 0;
        if (!allById.TryGetValue(LooseArtifactsRemovedId, out var toggle) || !toggle.IsToggle)
            throw new InvalidDataException("Missing loose artifact removal checkbox.");
        writtenParameters.Add(LooseArtifactsRemovedId);
        if (!toggle.CurrentBoolean)
            return 0;

        var rows = ReadStashCsv(LooseArtifactManifestResource, 5);
        if (rows.Count != 5
            || rows.Count(x => x[0] == "baseGame") != 4
            || rows.Count(x => x[0] == "dlc1") != 1)
            throw new InvalidDataException("Loose artifact source inventory drifted.");

        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (var row in rows)
        {
            var expectedSource = row[0] switch
            {
                "baseGame" => "GameData/SpawnActorPrototypes.cfg",
                "dlc1" => "DLCGameData/DLC1/SpawnActorPrototypes.cfg",
                _ => throw new InvalidDataException("Unknown loose artifact scope.")
            };
            if (row[1] != expectedSource || row[2] != "WorldMap_WP"
                || row[3].Length != 32 || !row[3].All(Uri.IsHexDigit)
                || !ids.Add(row[3])
                || !row[4].EndsWith("ArtifactSpawner", StringComparison.Ordinal)
                || !(row[4].StartsWith("Weird", StringComparison.Ordinal)
                     || row[4] == "WaterDripArtifactSpawner"))
                throw new InvalidDataException("Unsafe loose artifact actor " + row[3]);
        }

        var edits = 0;
        foreach (var row in rows.Where(x => IsScopeApplicable(x[0], hasDlc1)))
        {
            var path = GetSpawnActorRemovalOutputPath(outputRoot, row[1], row[2], row[3]);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path,
                "// Generated by True Custom Difficulty." + Environment.NewLine +
                "// Fixed non-quest artifact spot outside anomaly fields (" + row[4] + ")." + Environment.NewLine +
                row[3] + " : removenode" + Environment.NewLine,
                new UTF8Encoding(false));
            edits++;
        }
        return edits;
    }
}
